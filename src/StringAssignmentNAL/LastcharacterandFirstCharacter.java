package StringAssignmentNAL;

/*Write a program that will print out the last character and first character of a word.*/
public class LastcharacterandFirstCharacter {

	public static void main(String[] args) {

		String character = "Last and First";
		System.out.println(character.charAt(0));
		System.out.println(character.length());
		System.out.println(character.charAt(character.length() - 1));

	}

}
